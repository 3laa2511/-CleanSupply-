enum class AppLanguage(val code: String) {
    ARABIC("ar"),
    ENGLISH("en");

    companion object {
        fun fromCode(code: String?): AppLanguage =
            if (code == "en") ENGLISH else ARABIC
    }
}

private val Context.dataStore by preferencesDataStore(name = "cleansupply_prefs")

class LanguagePreferences(private val context: Context) {
    private val keyLang = stringPreferencesKey("preferred_locale")

    val languageFlow: Flow<AppLanguage> = context.dataStore.data.map { prefs ->
        AppLanguage.fromCode(prefs[keyLang])
    }

    suspend fun setLanguage(language: AppLanguage) {
        context.dataStore.edit { prefs ->
            prefs[keyLang] = language.code
        }
    }
}

