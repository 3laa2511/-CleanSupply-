enum class AppLanguage(val code: String) {
    ARABIC("ar"),
    ENGLISH("en");

    companion object {
        fun fromCode(code: String?): AppLanguage =
            if (code == "en") ENGLISH else ARABIC
    }
}

private val Context.dataStore by preferencesDataStore(name = "cleansupply_prefs")

class LanguagePreferences(private val context: Context) {
    private val keyLang = stringPreferencesKey("preferred_locale")
    private val keyTheme = stringPreferencesKey("preferred_theme")
    private val keyRecentSearches = stringPreferencesKey("recent_searches_csv")

    val languageFlow: Flow<AppLanguage> = context.dataStore.data.map { prefs ->
        AppLanguage.fromCode(prefs[keyLang])
    }

    val themeModeFlow: Flow<AppThemeMode> = context.dataStore.data.map { prefs ->
        AppThemeMode.fromCode(prefs[keyTheme])
    }

    val recentSearchesFlow: Flow<List<String>> = context.dataStore.data.map { prefs ->
        val raw = prefs[keyRecentSearches].orEmpty()
        if (raw.isBlank()) emptyList()
        else raw.split("||").map { it.trim() }.filter { it.isNotBlank() }
    }

    suspend fun setLanguage(language: AppLanguage) {
        context.dataStore.edit { prefs ->
            prefs[keyLang] = language.code
        }
    }

    suspend fun setThemeMode(mode: AppThemeMode) {
        context.dataStore.edit { prefs ->
            prefs[keyTheme] = mode.code
        }
    }

    suspend fun addRecentSearch(query: String) {
        val clean = query.trim()
        if (clean.length < 2) return
        context.dataStore.edit { prefs ->
            val current = prefs[keyRecentSearches].orEmpty()
                .split("||")
                .map { it.trim() }
                .filter { it.isNotBlank() && !it.equals(clean, ignoreCase = true) }
            val updated = (listOf(clean) + current).take(6)
            prefs[keyRecentSearches] = updated.joinToString("||")
        }
    }

    suspend fun clearRecentSearches() {
        context.dataStore.edit { prefs ->
            prefs.remove(keyRecentSearches)
        }
    }
}

